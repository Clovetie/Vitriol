/**
 * tools/lib/luau-native.js
 *
 * Bundles the pure TIDEKEEPER modules for execution in a REAL Luau VM.
 *
 * WHY THIS EXISTS, AND WHY IT IS NOT `lib/harness.js`
 * ---------------------------------------------------
 * `lib/harness.js` runs the same modules in fengari, a Lua 5.3 interpreter
 * written in JavaScript. Lua 5.3 is not Luau, and the differences are not
 * cosmetic: Lua 5.3 has two number subtypes where Luau has one, fengari's
 * integer subtype wraps at 32 bits, `bit32` does not exist, and
 * `string.format("%d", ...)` rejects the floats we are forced to use. The
 * harness therefore rewrites every integer literal to a float, shims `bit32`
 * over a 64 KB XOR table, and rewrites `%d` to `%.0f`. It works, it is
 * documented in tools/README.md section 5b, and it caught real bugs — but
 * every one of those workarounds is a difference between the code under test
 * and the code that ships.
 *
 * Luau is now available as a standalone binary (iteration 4 research, doc 10
 * section 7.1): the `luau` CLI from luau-lang/luau, and the Lute runtime built
 * on it. Running in real Luau needs NO transform except the Roblox `require`
 * rewrite, because everything else is simply the language the game is written
 * in. `255 * 16777216` is `4278190080` here and `-16777216` in fengari.
 *
 * WHAT THIS IS NOT
 * ----------------
 * The `luau` CLI is the same *language runtime* Roblox embeds, but it is not
 * the Roblox engine: no DataModel, no Roblox GC tuning, no Roblox build flags,
 * and the CLI's `--codegen` native path may or may not match what a Roblox
 * server enables. A number measured here is a real Luau number and a fair
 * order-of-magnitude answer. It is not a number measured on Roblox hardware.
 * Doc 09 section 4 calls this L3.5. Read the verdict text, not just the digits.
 */

"use strict";

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..", "..", "..");

/** Locate a usable `luau` binary, or return null. Never throws. */
function findLuau() {
	const candidates = [
		process.env.TIDEKEEPER_LUAU,
		path.join(ROOT, "tidekeeper", "tools", "bin", "luau"),
		"/tmp/luau/luau",
		"/usr/local/bin/luau",
		"/usr/bin/luau",
	].filter(Boolean);
	for (const c of candidates) {
		try {
			if (fs.existsSync(c) && fs.statSync(c).isFile()) return c;
		} catch (_) {
			/* keep looking */
		}
	}
	// Fall back to PATH.
	try {
		const found = execFileSync("sh", ["-c", "command -v luau || true"], {
			encoding: "utf8",
		}).trim();
		if (found) return found;
	} catch (_) {
		/* not on PATH */
	}
	return null;
}

/**
 * Rewrite Roblox instance-path requires to a flat name lookup.
 *
 * `require(script.Parent.Parent.Lib.Hash)` -> `TKRequire("Hash")`
 *
 * This is the ONLY source transform applied. Requires resolve by last path
 * segment, so module base names must be globally unique — the same constraint
 * the fengari harness has, and the quality gate's call-graph check enforces it.
 */
function rewriteRequires(src) {
	return src.replace(/require\(\s*([A-Za-z_][\w.:]*)\s*\)/g, (_all, p) => {
		const parts = p.split(".");
		return `TKRequire("${parts[parts.length - 1]}")`;
	});
}

/** Pick a long-bracket level that cannot collide with the source. */
function luaLongString(src) {
	let eq = 0;
	while (src.includes("]" + "=".repeat(eq) + "]")) eq += 1;
	const pad = "=".repeat(eq);
	return `[${pad}[\n${src}\n]${pad}]`;
}

const PREAMBLE = `
-- Generated by tools/lib/luau-native.js. Do not edit; edit the generator.
-- Runs in a real Luau VM, so there are no shims here. That is the point.
local SOURCES = {}
local CACHE = {}
local LOADING = {}

function TKRequire(name)
	local hit = CACHE[name]
	if hit ~= nil then
		return hit[1]
	end
	if LOADING[name] then
		error("require cycle through " .. name, 2)
	end
	local src = SOURCES[name]
	if src == nil then
		error("no such module: " .. tostring(name), 2)
	end
	LOADING[name] = true
	local chunk, err = loadstring(src, "@" .. name)
	if chunk == nil then
		error("compile error in " .. name .. ": " .. tostring(err), 2)
	end
	local value = chunk()
	LOADING[name] = nil
	CACHE[name] = { value }
	return value
end

-- The fengari harness injects the same resolver under the name
-- \`TidekeeperRequire\`, and tests/pure-tests.lua is shared verbatim between
-- the two runners -- so the alias is what lets ONE test file serve both VMs.
-- Without it the port would have needed a doctored copy of the suite, and a
-- doctored copy is exactly the thing this runner exists to get rid of.
TidekeeperRequire = TKRequire
`;

/**
 * Build a single .luau file: preamble, the module sources, then `body`.
 * @param {Object} modules  name -> absolute path of a .luau file
 * @param {string} body     the Luau chunk to run after the modules are loaded
 */
function buildBundle(modules, body) {
	const parts = [PREAMBLE];
	for (const [name, file] of Object.entries(modules)) {
		const src = rewriteRequires(fs.readFileSync(file, "utf8"));
		parts.push(`SOURCES[${JSON.stringify(name)}] = ${luaLongString(src)}`);
	}
	parts.push(body);
	return parts.join("\n");
}

/**
 * Write the bundle to `outFile` and execute it.
 * @returns {{ok: boolean, stdout: string, stderr: string, luau: string|null}}
 */
function runBundle(modules, body, outFile, opts) {
	const options = opts || {};
	const luau = findLuau();
	fs.mkdirSync(path.dirname(outFile), { recursive: true });
	fs.writeFileSync(outFile, buildBundle(modules, body), "utf8");
	if (!luau) return { ok: false, stdout: "", stderr: "", luau: null };

	const args = [];
	if (options.optimize !== false) args.push("-O2");
	if (options.codegen) args.push("--codegen");
	args.push(outFile);

	try {
		const stdout = execFileSync(luau, args, {
			encoding: "utf8",
			maxBuffer: 64 * 1024 * 1024,
			timeout: options.timeoutMs || 300000,
		});
		return { ok: true, stdout, stderr: "", luau };
	} catch (e) {
		return {
			ok: false,
			stdout: (e.stdout || "").toString(),
			stderr: (e.stderr || e.message || "").toString(),
			luau,
		};
	}
}

module.exports = { findLuau, rewriteRequires, buildBundle, runBundle };
